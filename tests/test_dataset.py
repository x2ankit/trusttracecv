class TestDuplicateFlooding:
    def _make_records(self, shas: list[str]) -> list[dict]:
        return [{"filename": f"img_{i}.jpg", "sha256": sha}
                for i, sha in enumerate(shas)]

    def test_no_duplicates(self):
        records = self._make_records(["aaa", "bbb", "ccc"])
        finding = check_duplicate_flooding(records)
        assert finding["result"] == "PASS"
        assert finding["evidence"]["duplicate_count"] == 0

    def test_duplicates_below_threshold(self):
        # 1 dup in 10 = 10%, threshold=5% → flagged
        records = self._make_records(["aaa"] * 2 + [str(i) for i in range(8)])
        finding = check_duplicate_flooding(records, threshold_pct=0.05)
        assert finding["result"] == "ANOMALY_DETECTED"

    def test_single_image_no_dup(self):
        records = self._make_records(["unique"])
        finding = check_duplicate_flooding(records)
        assert finding["result"] == "PASS"

    def test_check_id(self):
        records = self._make_records(["x"])
        finding = check_duplicate_flooding(records)
        assert finding["check_id"] == "SEC-DS-001"


