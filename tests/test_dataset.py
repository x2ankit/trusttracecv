class TestInspectImage:
    def test_basic_record_keys(self, tmp_path):
        img_path = _make_rgb_image(tmp_path / "img.jpg")
        rec = inspect_image(img_path)
        assert rec["filename"] == "img.jpg"
        assert rec["width"] == 100
        assert rec["height"] == 100
        assert len(rec["sha256"]) == 64
        assert rec["checks"]["file_exists"]["result"] == "PASS"
        assert rec["checks"]["image_readable"]["result"] == "PASS"

    def test_missing_file(self, tmp_path):
        rec = inspect_image(tmp_path / "nonexistent.jpg")
        assert rec["checks"]["file_exists"]["result"] == "FAIL"

    def test_blank_image_warn(self, tmp_path):
        img_path = _make_rgb_image(tmp_path / "blank.jpg", colour=(128, 128, 128))
        rec = inspect_image(img_path)
        # Uniform image → std < 1 → WARN
        assert rec["checks"]["non_blank"]["result"] == "WARN"

    def test_yolo_annotation_valid(self, tmp_path):
        img_path = _make_rgb_image(tmp_path / "img.jpg")
        lbl_path = _make_yolo_label(tmp_path / "img.txt", ["0 0.5 0.5 0.2 0.2"])
        rec = inspect_image(img_path, lbl_path, format="yolo")
        assert rec["checks"]["annotation_valid"]["result"] == "PASS"
        assert len(rec["annotations"]) == 1
        assert rec["annotations"][0]["class_id"] == 0

    def test_yolo_annotation_oob(self, tmp_path):
        img_path = _make_rgb_image(tmp_path / "img.jpg")
        lbl_path = _make_yolo_label(tmp_path / "img.txt", ["0 1.5 0.5 0.2 0.2"])
        rec = inspect_image(img_path, lbl_path, format="yolo")
        assert rec["checks"]["annotation_valid"]["result"] == "FAIL"

    def test_sha256_deterministic(self, tmp_path):
        img_path = _make_rgb_image(tmp_path / "img.jpg", colour=(50, 60, 70))
        sha1 = _sha256_file(img_path)
        sha2 = _sha256_file(img_path)
        assert sha1 == sha2

    def test_sha256_differs_for_different_images(self, tmp_path):
        p1 = _make_rgb_image(tmp_path / "a.jpg", colour=(10, 20, 30))
        p2 = _make_rgb_image(tmp_path / "b.jpg", colour=(200, 180, 160))
        assert _sha256_file(p1) != _sha256_file(p2)


